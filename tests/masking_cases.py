def _luhn_number(prefix: str, length: int) -> str:
    body = prefix + "0" * (length - len(prefix) - 1)
    for check_digit in "0123456789":
        candidate = body + check_digit
        checksum = 0
        for index, digit in enumerate(reversed(candidate)):
            value = int(digit)
            if index % 2:
                value *= 2
                if value > 9:
                    value -= 9
            checksum += value
        if checksum % 10 == 0:
            return candidate
    raise AssertionError("no Luhn check digit")


